#!/usr/bin/env python3
"""Check the reviewed macOS 27 (26C5035r) IOMobileFramebufferLegacy ABI fixture.

The fixture is the source of truth for the legacy display ABI: the vtable slot
count, every slot's pointer-authentication diversity, the instance extent and
the field offsets the GopFramebuffer backend reads. It was generated by
`gen-board-abi.py --build 26C5035r` from the same kernelcache the TB710FU prelink
consumes (`upstream.lock.json:kernelcache_sha256`).

The structural checks always run. `--kernel` additionally proves the fixture
against this board's own prelinked `kernel.macho`: the class vtable is at the
fixture address plus the collection slide, and every one of the 483 slots carries
the reviewed authenticated-pointer diversity. That is the fact that lets
`package/GopDisplayStart.cpp` find the live original vtable at boot without
hard-coding a single code address.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

FIXTURE = Path(__file__).resolve().with_name('legacy-display-26C5035r.json')
LOCK = Path(__file__).resolve().parents[1] / 'upstream.lock.json'

INSTANCE_SIZE = 0x23a0
BASE_SLOTS = 272
SLOT_COUNT = 483
# Four macOS-gated family slots (setNotifyTagMaskGated 318, supportedFrameInfo 320,
# factoryPortal 361, executeFactoryConfigurations 362) are rebound by XnuPrelink to a
# single native function, so their live entry carries that function's discriminator.
REBOUND_SLOTS = (318, 320, 361, 362)
SURFACE_FIELDS = {
    'descriptor': (0x30, 8),
    'width': (0x58, 8),
    'height': (0x60, 8),
    'stride': (0x68, 8),
    'format': (0x80, 4),
    'planes': (0x98, 4),
}


def discriminator(name):
    """clang ptrauth_string_discriminator: SipHash-2-4 with the fixed key, modulo 0xffff, plus one."""
    mask = (1 << 64) - 1
    rotl = lambda x, b: ((x << b) | (x >> (64 - b))) & mask  # noqa: E731
    key = bytes([0xb5, 0xd4, 0xc9, 0xeb, 0x79, 0x10, 0x4a, 0x79,
                 0x6f, 0xec, 0x8b, 0x1b, 0x42, 0x87, 0x81, 0xd4])
    k0, k1 = struct.unpack('<2Q', key)
    v = [0x736f6d6570736575 ^ k0, 0x646f72616e646f6d ^ k1,
         0x6c7967656e657261 ^ k0, 0x7465646279746573 ^ k1]

    def rounds(n):
        for _ in range(n):
            v[0] = (v[0] + v[1]) & mask; v[1] = rotl(v[1], 13) ^ v[0]; v[0] = rotl(v[0], 32)
            v[2] = (v[2] + v[3]) & mask; v[3] = rotl(v[3], 16) ^ v[2]
            v[0] = (v[0] + v[3]) & mask; v[3] = rotl(v[3], 21) ^ v[0]
            v[2] = (v[2] + v[1]) & mask; v[1] = rotl(v[1], 17) ^ v[2]; v[2] = rotl(v[2], 32)

    data = name.encode()
    full = len(data) & ~7
    for i in range(0, full, 8):
        m = struct.unpack_from('<Q', data, i)[0]
        v[3] ^= m; rounds(2); v[0] ^= m
    b = (len(data) << 56) & mask
    for i, c in enumerate(data[full:]):
        b |= c << (8 * i)
    v[3] ^= b; rounds(2); v[0] ^= b; v[2] ^= 0xff; rounds(4)
    return (v[0] ^ v[1] ^ v[2] ^ v[3]) % 0xffff + 1


def check_ioservice_base(fixture):
    """The IOService half of the adopted table must carry the call-site ABI values.

    pl43 started owning the six IOService virtuals the backend overrides, and the
    runtime re-signs those entries with tb710fu_gop_slot_diversity[slot]. That is
    only correct if the fixture's value at that slot is the discriminator every
    call site builds (slot address | disc << 48), so verify it against the base
    declaration's string hash for the three slots that resolve uniquely here:
    start at slot 190 (0x3c68, the movk #0x3c68 the 26C5035r call site uses),
    stop at 191, registerService at 188. free, setPowerState and the two
    newUserClient overloads are covered by the compiled-vs-fixture comparison in
    scripts/build-tb710fu-gop-display.py, because their mangled variance differs.
    """
    slots = [int(d, 16) for _, d in fixture['slots']]
    expected = {
        'registerService': '_ZN9IOService15registerServiceEj',
        'start': '_ZN9IOService5startEPS_',
        'stop': '_ZN9IOService4stopEPS_',
    }
    found = {}
    for name, mangled in expected.items():
        want = discriminator(mangled)
        hits = [i for i, value in enumerate(slots) if value == want and i < BASE_SLOTS]
        assert len(hits) == 1, f'IOService::{name} diversity {want:#x} is not one base slot: {hits}'
        found[name] = hits[0]
    assert found['registerService'] < found['start'] < found['stop'], 'IOService slot order changed'
    return found


def check_fixture(fixture):
    """Structural facts the generated header and the runtime adoption depend on."""
    slots = [(int(t, 16), int(d, 16)) for t, d in fixture['slots']]
    assert len(slots) == SLOT_COUNT, f'legacy vtable is {len(slots)} slots, expected {SLOT_COUNT}'
    assert fixture['base_slots'] == BASE_SLOTS, 'IOService base vtable length changed'
    assert int(fixture['instance_size'], 16) == INSTANCE_SIZE, 'legacy instance extent changed'
    assert len(fixture['names']) == SLOT_COUNT - BASE_SLOTS, 'one reviewed name per legacy slot'
    assert all(d for _, d in slots), 'every slot carries a non-zero diversity'

    methods = {name: int(slot) for name, slot in fixture['methods'].items()}
    assert all(BASE_SLOTS <= slot < SLOT_COUNT for slot in methods.values()), 'method slot out of range'
    for label, slot in methods.items():
        assert label in fixture['names'], f'{label}: named slot has no reviewed name'

    names = fixture['names']
    for base, (name, suffix) in names.items():
        if base in methods:
            slot = methods[base]
        else:
            assert base.startswith('opaque'), f'{base}: unreviewed name key'
            slot = int(base[len('opaque'):])
        mangled = f'_ZN25IOMobileFramebufferLegacy{len(name)}{name}{suffix}'
        assert discriminator(mangled) == slots[slot][1], f'{base}: reviewed name has slot {slot} diversity'

    display, request = fixture['display'], fixture['request']
    assert display['current'] < display['head'] < display['tail'] < display['vsync_clients'], 'display order'
    assert display['width'] + 4 == display['height'] or display['width'] < display['height'], 'display dims'
    assert display['default_surface'] < SLOT_COUNT + 0x2000, 'display field offsets are within the instance'
    assert request['rect0'] < request['rect1'] < request['masks'] < request['options'], 'request order'
    assert request['dims'] < request['surfaces'] < request['next'] < request['prev'], 'request tail order'
    assert all(offset < INSTANCE_SIZE for offset in (display['width'], display['height'],
                                                    display['head'], display['current'])), 'display offsets'

    checks = fixture['checks']
    assert len(checks) == len(SURFACE_FIELDS), 'one check stub per IOSurface accessor'
    decoded = []
    for index, ((target, code), (field, (offset, width))) in enumerate(zip(checks, SURFACE_FIELDS.items())):
        words = struct.unpack('<3I', bytes.fromhex(code))
        assert words[0] == 0xd503245f, f'{field}: stub does not start with bti c'
        instruction = words[1]
        scale = 8 if (instruction & 0xffc00000) == 0xf9400000 else 4
        assert scale == width, f'{field}: accessor width differs from the layout'
        immediate = ((instruction >> 10) & 0xfff) * scale
        assert (instruction & 31) == 0 and ((instruction >> 5) & 31) == 0, f'{field}: stub is not a leaf load'
        assert immediate == offset, f'{field}: accessor reads {immediate:#x}, expected {offset:#x}'
        decoded.append({'field': field, 'offset': offset, 'width': width, 'stub': target})

    return {
        'instance_size': INSTANCE_SIZE,
        'base_slots': BASE_SLOTS,
        'slot_count': SLOT_COUNT,
        'diversity': hashlib.sha256(''.join(f'{d:04x}' for _, d in slots).encode()).hexdigest(),
        'ioservice_base_slots': check_ioservice_base(fixture),
        'surface_accessors': decoded,
        'collection_slide': fixture['collection_slide'],
        'vtable': fixture['vtable'],
        'metaclass': fixture['bindings']['__ZN25IOMobileFramebufferLegacy10gMetaClassE'],
        'kernelcache_sha256': fixture['kernelcache_sha256'],
    }


def check_kernel(fixture, kernel):
    """Prove the reviewed vtable against this board's prelinked fileset."""
    data = Path(kernel).read_bytes()
    commands = struct.unpack_from('<I', data, 16)[0]
    offset, segments = 32, []
    for _ in range(commands):
        command, size = struct.unpack_from('<2I', data, offset)
        if command == 0x19:
            va, vsize, fileoff, filesize = struct.unpack_from('<QQQQ', data, offset + 24)
            segments.append((va, vsize, fileoff, filesize))
        offset += size

    def read_va(va, length):
        for sva, vsize, fileoff, filesize in segments:
            if sva <= va and va + length <= sva + min(vsize, filesize) and fileoff:
                return data[fileoff + (va - sva):fileoff + (va - sva) + length]
        raise AssertionError(f'{va:#x} is not file-backed in the prelinked kernel')

    slide = int(fixture['collection_slide'], 16)
    vtable = int(fixture['vtable'], 16) + slide
    raw = read_va(vtable, 8 * SLOT_COUNT)
    slots = [(int(t, 16), int(d, 16)) for t, d in fixture['slots']]
    matched, rebound, relocated = 0, [], 0
    for index, (target, diversity) in enumerate(slots):
        word = struct.unpack_from('<Q', raw, index * 8)[0]
        if word >> 63 != 1:
            raise AssertionError(f'slot {index}: vtable entry is not an authenticated pointer')
        actual = (word >> 32) & 0xffff
        if actual == diversity:
            matched += 1
        elif index not in REBOUND_SLOTS:
            raise AssertionError(f'slot {index}: diversity {actual:#x} != {diversity:#x}')
        else:
            rebound.append(index)
            continue
        if word & 0xffffffff == (target + slide) & 0xffffffff:
            pass
        else:
            relocated += 1
    assert sorted(rebound) == sorted(REBOUND_SLOTS), f'rebound slots {rebound} differ from {REBOUND_SLOTS}'
    return {'kernel': str(kernel), 'vtable_slide_address': f'{vtable:#x}', 'slots': SLOT_COUNT,
            'diversity_match': matched, 'rebound_slots': rebound,
            'entries_at_fixture_target': SLOT_COUNT - relocated - len(rebound),
            'entries_relocated': relocated}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fixture', type=Path, default=FIXTURE)
    parser.add_argument('--kernel', type=Path, help='prelinked kernel.macho to check the vtable against')
    parser.add_argument('--report', type=Path, help='write the JSON report here')
    args = parser.parse_args()

    fixture = json.loads(args.fixture.read_text())
    lock = json.loads(LOCK.read_text())
    assert fixture['kernelcache_sha256'] == lock['kernelcache_sha256'], 'fixture is not the pinned 26C5035r kernelcache'
    assert lock['os_profile'].endswith(fixture['build']), 'fixture build differs from the pinned OS profile'
    assert fixture['abi'] == 'macos', 'fixture is not the macOS family ABI'

    report = {'fixture': str(args.fixture), 'fixture_sha256': hashlib.sha256(args.fixture.read_bytes()).hexdigest()}
    report.update(check_fixture(fixture))
    if args.kernel:
        report.update(check_kernel(fixture, args.kernel))
    text = json.dumps(report, indent=2) + '\n'
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(text)
    print(text, end='')


if __name__ == '__main__':
    main()
