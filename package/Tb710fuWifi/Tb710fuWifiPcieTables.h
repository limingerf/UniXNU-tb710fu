/* SM8650 PCIe0 QMP PHY (Gen3 x2, TB710FU 0x1c06000) init values as (offset from the PHY base, value).
 *
 * Provenance: sm8650.dtsi phy@1c06000 is "qcom,sm8650-qmp-gen3x2-pcie-phy"; upstream Linux maps that compatible to
 * sm8550_qmp_gen3x2_pciephy_cfg (drivers/phy/qualcomm/phy-qcom-qmp-pcie.c), whose offsets are qmp_pcie_offsets_v5:
 * serdes 0x0, pcs 0x200, pcs_misc 0x600, tx 0xe00, rx 0x1000, lane 2 tx 0x1600 and rx 0x1800. The values below are that
 * configuration's tables, the same ones UniXNU-sheng's hardware-verified WifiPcieTables.h carries for the identical
 * controller: serdes 37 writes, tx 5, rx 25, pcs 5, pcs_misc 6. v5 PCS registers: sw_reset 0x200, pcs_status1 0x214
 * (bit 6 PHYSTATUS), power_down_control 0x240, start_control 0x244. */
